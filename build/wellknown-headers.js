'use strict'

// Generates deps/llhttp/src/undici_wellknown_headers.h from wellknownHeaderNames
// in lib/core/constants.js. The WASM glue uses it to report a lowercased header
// name's 1-based index in that list, so the client can reuse a preallocated
// string for a well-known name instead of decoding a new one.
//
// `npm run build:wasm` runs this first; test/node-test/wellknown-headers.js
// fails when the committed header is stale.

const { writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { wellknownHeaderNames } = require('../lib/core/constants.js')

const OUT = join(__dirname, '../deps/llhttp/src/undici_wellknown_headers.h')

/**
 * @param {Buffer} bytes
 * @returns {string} the bytes as a little-endian integer literal
 */
function literal (bytes) {
  let value = 0n
  for (let i = bytes.length - 1; i >= 0; i--) {
    value = (value << 8n) | BigInt(bytes[i])
  }
  return `0x${value.toString(16)}${bytes.length === 8 ? 'ULL' : 'U'}`
}

/**
 * Compares `at[0, length)` with `name` using word loads. Overlapping loads
 * cover a tail, so a name costs at most ceil(length / 8) + 1 compares.
 *
 * @param {string} name
 * @returns {string}
 */
function compare (name) {
  const bytes = Buffer.from(name, 'latin1')
  const n = bytes.length
  const terms = []
  const load = (offset, size) => {
    terms.push(`undici_load${size * 8}(at + ${offset}) == ${literal(bytes.subarray(offset, offset + size))}`)
  }

  if (n >= 8) {
    for (let i = 0; i + 8 <= n; i += 8) {
      load(i, 8)
    }
    if (n % 8 !== 0) {
      load(n - 8, 8)
    }
  } else if (n >= 4) {
    load(0, 4)
    if (n > 4) {
      load(n - 4, 4)
    }
  } else if (n >= 2) {
    load(0, 2)
    if (n > 2) {
      load(n - 2, 2)
    }
  } else {
    load(0, 1)
  }

  return terms.join(' &&\n          ')
}

function generate () {
  const byLength = new Map()
  const seen = new Set()
  wellknownHeaderNames.forEach((header, i) => {
    const name = header.toLowerCase()
    if (seen.has(name) || !/^[!#$%&'*+\-.^_`|~0-9a-z]+$/.test(name)) {
      throw new Error(`invalid well-known header name: ${header}`)
    }
    seen.add(name)
    if (!byLength.has(name.length)) {
      byLength.set(name.length, [])
    }
    byLength.get(name.length).push({ name, index: i + 1 })
  })

  const cases = [...byLength.keys()].sort((a, b) => a - b).map((length) => {
    const checks = byLength.get(length).map(({ name, index }) => `      if (${compare(name)}) {
        return ${index};  /* ${name} */
      }`).join('\n')
    return `    case ${length}:
${checks}
      return 0;`
  }).join('\n')

  return `/* Generated by build/wellknown-headers.js from wellknownHeaderNames in
 * lib/core/constants.js. Do not edit. */

#ifndef UNDICI_WELLKNOWN_HEADERS_H_
#define UNDICI_WELLKNOWN_HEADERS_H_

#include <stddef.h>
#include <stdint.h>
#include <string.h>

static uint8_t undici_load8(const char* p) {
  return (uint8_t) *p;
}

static uint16_t undici_load16(const char* p) {
  uint16_t v;
  memcpy(&v, p, sizeof(v));
  return v;
}

static uint32_t undici_load32(const char* p) {
  uint32_t v;
  memcpy(&v, p, sizeof(v));
  return v;
}

static uint64_t undici_load64(const char* p) {
  uint64_t v;
  memcpy(&v, p, sizeof(v));
  return v;
}

/* Returns the 1-based index of a lowercased header name in
 * wellknownHeaderNames, or 0 when it is not one of them. Loads are
 * little-endian, as in WebAssembly. */
static int undici_wellknown_header(const char* at, size_t length) {
  switch (length) {
${cases}
    default:
      return 0;
  }
}

#endif  /* UNDICI_WELLKNOWN_HEADERS_H_ */
`
}

module.exports = { OUT, generate }

if (require.main === module) {
  writeFileSync(OUT, generate())
}
